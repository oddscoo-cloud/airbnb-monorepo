interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (text: string) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    if (typeof window === 'undefined') return 'uk'
    try {
      return localStorage.getItem('homefu-language') === 'en' ? 'en' : 'uk'
    } catch (error) {
      console.error('Could not read the saved language preference', error)
      return 'uk'
    }
  })
  const languageRef = useRef(language)
  languageRef.current = language

  useEffect(() => {
    document.documentElement.lang = language
    try {
      localStorage.setItem('homefu-language', language)
    } catch (error) {
      console.error('Could not save the language preference', error)
    }
  }, [language])

  const t = useCallback((text: string) =>
    languageRef.current === 'en' ? translations[text] ?? text : text, [])
  const value = useMemo(() => ({ language, setLanguage, t }), [language, t])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within LanguageProvider')
  return context
}
